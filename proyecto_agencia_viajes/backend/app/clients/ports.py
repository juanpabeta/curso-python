from typing import Protocol

from app.clients.models import ClientModel, CompanionModel


class ClientRepository(Protocol):
    def add(self, client: ClientModel) -> ClientModel: ...
    def get(self, client_id: int) -> ClientModel | None: ...
    def list(self, query: str | None = None) -> list[ClientModel]: ...
    def update(self, client: ClientModel) -> ClientModel: ...
    def add_companion(self, client_id: int, companion: CompanionModel) -> CompanionModel: ...
    def delete(self, client_id: int) -> None: ...
