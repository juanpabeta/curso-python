from datetime import datetime
from typing import Protocol

from app.reminders.models import ReminderModel


class ReminderRepository(Protocol):
    def add(self, item: ReminderModel) -> ReminderModel: ...
    def get(self, item_id: int) -> ReminderModel | None: ...
    def update(self, item: ReminderModel) -> ReminderModel: ...
    def list_due(self, now: datetime) -> list[ReminderModel]: ...
